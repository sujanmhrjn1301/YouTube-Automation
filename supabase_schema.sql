-- ==============================================================================
-- Supabase PostgreSQL Schema for YouTube Shorts Automation Pipeline
-- Run this script in your Supabase Dashboard: SQL Editor -> New Query -> Run
-- ==============================================================================

-- 1. Main Shorts Metadata Table
CREATE TABLE IF NOT EXISTS public.shorts_metadata (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url TEXT NOT NULL,
    source_video_id TEXT,
    source_title TEXT,
    hook_title TEXT NOT NULL,
    description TEXT,
    tags TEXT[],
    viral_reasoning TEXT,
    hook_score INTEGER,
    start_time NUMERIC,
    end_time NUMERIC,
    duration NUMERIC,
    storage_url TEXT,
    youtube_id TEXT,
    part_number INTEGER DEFAULT 1,
    total_parts INTEGER DEFAULT 1,
    is_confirmed_uploaded BOOLEAN DEFAULT FALSE,
    confirmed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for lightning-fast duplicate checking and queries
CREATE INDEX IF NOT EXISTS idx_shorts_metadata_source_video_id 
    ON public.shorts_metadata(source_video_id);

CREATE INDEX IF NOT EXISTS idx_shorts_metadata_youtube_id 
    ON public.shorts_metadata(youtube_id);

CREATE INDEX IF NOT EXISTS idx_shorts_metadata_hook_title 
    ON public.shorts_metadata(hook_title);


-- 2. Multi-Part Video Series Linking Table
CREATE TABLE IF NOT EXISTS public.video_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_video_id TEXT NOT NULL,
    source_title TEXT NOT NULL,
    source_url TEXT NOT NULL,
    part_number INTEGER NOT NULL,
    total_parts INTEGER NOT NULL,
    short_title TEXT NOT NULL,
    duration NUMERIC NOT NULL,
    youtube_id TEXT,
    youtube_url TEXT,
    is_confirmed BOOLEAN DEFAULT FALSE,
    confirmed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_video_series_source_part UNIQUE (source_video_id, part_number)
);

CREATE INDEX IF NOT EXISTS idx_video_series_source_video_id 
    ON public.video_series(source_video_id);


-- 3. Row-Level Security (RLS) Configuration
-- Enable RLS for production security
ALTER TABLE public.shorts_metadata ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.video_series ENABLE ROW LEVEL SECURITY;

-- Allow service role full access (used by the pipeline's SUPABASE_SERVICE_ROLE_KEY)
DROP POLICY IF EXISTS "Service role full access on shorts_metadata" ON public.shorts_metadata;
CREATE POLICY "Service role full access on shorts_metadata" 
    ON public.shorts_metadata 
    FOR ALL 
    USING (auth.role() = 'service_role' OR auth.role() = 'anon');

DROP POLICY IF EXISTS "Service role full access on video_series" ON public.video_series;
CREATE POLICY "Service role full access on video_series" 
    ON public.video_series 
    FOR ALL 
    USING (auth.role() = 'service_role' OR auth.role() = 'anon');
